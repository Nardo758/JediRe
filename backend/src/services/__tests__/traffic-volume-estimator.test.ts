import { describe, it, expect } from 'vitest';
import {
  CalibrationObservation,
  MIN_CALIBRATION_OBSERVATIONS,
  MIN_IDENTIFIABLE_RATIO,
  ROAD_CLASSES,
  SpeedFlowParams,
  defaultSpeedFlowParams,
  estimateHourlyVolume,
  evaluateCrossCheck,
  fitSpeedFlowParams,
  identifiabilityFloor,
  invertSpeedFlow,
  toRoadClass,
} from '../traffic-volume-estimator';

/** Forward BPR curve, used to build inputs with a known answer. */
const travelTimeRatio = (vc: number, params: SpeedFlowParams): number => 1 + params.alpha * Math.pow(vc, params.beta);

describe('invertSpeedFlow', () => {
  it.each(ROAD_CLASSES)('recovers v/c from the travel-time ratio for %s', (roadClass) => {
    const params = defaultSpeedFlowParams(roadClass);
    for (const vc of [0.7, 0.85, 1.0, 1.15]) {
      const result = invertSpeedFlow(travelTimeRatio(vc, params), params);
      expect(result.status).toBe('ok');
      expect(result.vcRatio).toBeCloseTo(vc, 10);
    }
  });

  it.each(ROAD_CLASSES)('clamps readings above the invertible range for %s', (roadClass) => {
    const params = defaultSpeedFlowParams(roadClass);
    const result = invertSpeedFlow(travelTimeRatio(1.6, params), params);
    expect(result).toEqual({ vcRatio: params.maxVcRatio, status: 'clamped' });
  });

  it('treats a reading exactly at the clamp as ok, not clamped', () => {
    const params = defaultSpeedFlowParams('Arterial');
    const result = invertSpeedFlow(travelTimeRatio(params.maxVcRatio, params), params);
    expect(result.status).toBe('ok');
    expect(result.vcRatio).toBeCloseTo(params.maxVcRatio, 10);
  });

  it.each([0.5, 0.97, 1.0, 1.019])('reports ratio %s as free flow, capped at the identifiability floor', (ratio) => {
    const params = defaultSpeedFlowParams('Arterial');
    const result = invertSpeedFlow(ratio, params);
    expect(result.status).toBe('free_flow');
    expect(result.vcRatio).toBeCloseTo(identifiabilityFloor(params), 12);
  });

  it('starts inverting at the identifiability threshold', () => {
    const params = defaultSpeedFlowParams('Arterial');
    const result = invertSpeedFlow(MIN_IDENTIFIABLE_RATIO, params);
    expect(result.status).toBe('ok');
    expect(result.vcRatio).toBeCloseTo(identifiabilityFloor(params), 12);
  });

  it.each([0, -1, Number.NaN, Number.POSITIVE_INFINITY])('rejects travel-time ratio %s', (ratio) => {
    expect(() => invertSpeedFlow(ratio, defaultSpeedFlowParams('Local'))).toThrow(RangeError);
  });

  it('rejects non-positive parameters', () => {
    const params = { ...defaultSpeedFlowParams('Local'), alpha: 0 };
    expect(() => invertSpeedFlow(1.2, params)).toThrow(/alpha/);
  });
});

describe('estimateHourlyVolume', () => {
  const params = defaultSpeedFlowParams('Arterial');

  it('uses the DOT station lane count when there is one', () => {
    const estimate = estimateHourlyVolume({
      freeFlowSeconds: 100,
      inTrafficSeconds: 100 * travelTimeRatio(0.9, params),
      lanes: 6,
      params,
    });
    expect(estimate.lanesSource).toBe('dot_station');
    expect(estimate.lanesUsed).toBe(6);
    expect(estimate.volumeVph).toBeCloseTo(0.9 * 6 * params.capacityPerLaneVph, 6);
  });

  it('falls back to the class default lanes and says so', () => {
    const estimate = estimateHourlyVolume({
      freeFlowSeconds: 100,
      inTrafficSeconds: 100 * travelTimeRatio(0.9, params),
      lanes: null,
      params,
    });
    expect(estimate.lanesSource).toBe('class_default');
    expect(estimate.volumeVph).toBeCloseTo(0.9 * params.defaultLanes * params.capacityPerLaneVph, 6);
  });

  it('marks results from the built-in defaults as uncalibrated', () => {
    const input = { freeFlowSeconds: 100, inTrafficSeconds: 110, lanes: 4 };
    expect(estimateHourlyVolume({ ...input, params }).calibrated).toBe(false);
    expect(estimateHourlyVolume({ ...input, params: { ...params, scope: 'road_class' } }).calibrated).toBe(true);
  });

  it('rejects non-positive durations', () => {
    expect(() => estimateHourlyVolume({ freeFlowSeconds: 0, inTrafficSeconds: 100, lanes: 4, params })).toThrow(
      RangeError,
    );
    expect(() => estimateHourlyVolume({ freeFlowSeconds: 100, inTrafficSeconds: -5, lanes: 4, params })).toThrow(
      RangeError,
    );
  });
});

describe('fitSpeedFlowParams', () => {
  const base = defaultSpeedFlowParams('Arterial');
  const options = { scope: 'road_class' as const, source: 'fit:test', calibratedAt: '2026-11-12T00:00:00.000Z' };
  const lanes = 4;

  const observationsFrom = (truth: SpeedFlowParams, vcs: number[]): CalibrationObservation[] =>
    vcs.map((vc) => ({
      travelTimeRatio: travelTimeRatio(vc, truth),
      dotHourlyCountVph: vc * lanes * truth.capacityPerLaneVph,
      lanes,
    }));

  it('recovers alpha and beta from DOT hourly counts generated by a known curve', () => {
    const truth = { ...base, alpha: 0.3, beta: 3 };
    const fit = fitSpeedFlowParams(observationsFrom(truth, [0.6, 0.65, 0.7, 0.8, 0.9, 1.0, 1.05, 1.1, 1.15]), base, options);
    expect(fit.status).toBe('ok');
    if (fit.status !== 'ok') return;
    expect(fit.params.alpha).toBeCloseTo(0.3, 8);
    expect(fit.params.beta).toBeCloseTo(3, 8);
    expect(fit.params.fitR2).toBeCloseTo(1, 8);
    expect(fit.params).toMatchObject({
      scope: 'road_class',
      source: 'fit:test',
      calibratedAt: '2026-11-12T00:00:00.000Z',
      sampleCount: 9,
      capacityPerLaneVph: base.capacityPerLaneVph,
    });
  });

  it('leaves out free-flow and over-capacity readings', () => {
    const truth = { ...base, alpha: 0.3, beta: 3 };
    const usable = observationsFrom(truth, [0.6, 0.7, 0.8, 0.9, 1.0, 1.05, 1.1, 1.15]);
    const unusable: CalibrationObservation[] = [
      { travelTimeRatio: 1.0, dotHourlyCountVph: 400, lanes },
      { travelTimeRatio: 2.4, dotHourlyCountVph: 1.5 * lanes * base.capacityPerLaneVph, lanes },
    ];
    const fit = fitSpeedFlowParams([...usable, ...unusable], base, options);
    expect(fit.status).toBe('ok');
    expect(fit.usedObservations).toBe(usable.length);
  });

  it('reports too few observations instead of fitting', () => {
    const fit = fitSpeedFlowParams(observationsFrom(base, [0.7, 0.8, 0.9]), base, options);
    expect(fit).toEqual({
      status: 'insufficient_observations',
      usedObservations: 3,
      required: MIN_CALIBRATION_OBSERVATIONS,
    });
  });

  it('reports a degenerate fit when every observation has the same v/c', () => {
    const fit = fitSpeedFlowParams(observationsFrom(base, new Array(10).fill(0.9)), base, options);
    expect(fit.status).toBe('degenerate');
  });

  it('reports a degenerate fit when travel time falls as volume rises', () => {
    const vcs = [0.6, 0.65, 0.7, 0.75, 0.8, 0.85, 0.9, 0.95, 1.0];
    const backwards: CalibrationObservation[] = vcs.map((vc, i) => ({
      travelTimeRatio: 1.5 - i * 0.04,
      dotHourlyCountVph: vc * lanes * base.capacityPerLaneVph,
      lanes,
    }));
    const fit = fitSpeedFlowParams(backwards, base, options);
    expect(fit.status).toBe('degenerate');
  });
});

describe('evaluateCrossCheck', () => {
  it('flags the absence of a cross-check', () => {
    expect(evaluateCrossCheck(1000, null, 20)).toEqual({ status: 'no_cross_check' });
  });

  it('agrees inside the tolerance and diverges outside it', () => {
    const reading = { source: 'dot_continuous_counter', volumeVph: 1000, observedAt: '2026-11-12T12:00:00.000Z' };
    expect(evaluateCrossCheck(1150, reading, 20)).toMatchObject({
      status: 'agree',
      differencePct: expect.closeTo(15, 6),
    });
    expect(evaluateCrossCheck(1300, reading, 20)).toMatchObject({
      status: 'diverge',
      source: 'dot_continuous_counter',
      referenceVolumeVph: 1000,
    });
  });
});

describe('toRoadClass', () => {
  it('maps DOT functional classes onto the five profile classes', () => {
    expect(toRoadClass('Principal Arterial')).toBe('Arterial');
    expect(toRoadClass(' freeway ')).toBe('Expressway');
    expect(toRoadClass('Interstate')).toBe('Interstate');
  });

  it('returns null for a missing or unknown class instead of guessing', () => {
    expect(toRoadClass(null)).toBeNull();
    expect(toRoadClass('Ramp')).toBeNull();
  });
});
